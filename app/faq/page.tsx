function AccordionItem({ q, a }: { q: string; a: string }) {
  const [open, setOpen] = useState(false);

  return (
    <div className="border-b border-[rgba(196,168,130,0.2)] last:border-0">
      <button
        onClick={() => setOpen(!open)}
        className="w-full text-left py-5 flex items-center justify-between gap-4"
      >
        <span className="text-sm font-normal text-[#5C3820] leading-relaxed">{q}</span>
        <span className={`text-[#C4A882] text-lg flex-shrink-0 transition-transform ${open ? "rotate-45" : ""}`}>+</span>
      </button>
      {open && (
        <div className="pb-5 pr-8">
          {a.split("\n").map((line, i) => (
            <p key={i} className="text-sm font-light text-[#7A6055] leading-relaxed mb-2 last:mb-0">
              {line}
            </p>
          ))}
        </div>
      )}
    </div>
  );
}

